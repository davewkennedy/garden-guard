#!/usr/bin/env node
// Garden Guard music: render, level and encode (owner: Dale).
//   node tools/music/build.js        -> web/audio/{music-build,music-wave,stinger-win,stinger-lose}.mp3
//                                       + web/audio/music.json, then checks the result (see QA below)
// Needs ffmpeg with libmp3lame: $FFMPEG, else `ffmpeg` on PATH, else the Windows one
// (/mnt/c/ProgramData/chocolatey/bin/ffmpeg.exe, called with Windows paths from WSL).
//
// LEVELS: loops -20 LUFS integrated (measured over exactly one loop), stingers -16 LUFS; true peak
// <= -3 dBTP (if the target would exceed it, the gain is lowered instead: never limited or
// compressed, so the loops stay exactly periodic). Gain is one linear volume change.
// QA (prints PASS/FAIL, exit 1 on a FAIL): decodes every MP3 again and checks
//   - loudness and true peak of the decoded MP3;
//   - loop seam: the decoded signal around loopStart equals the signal one loop later (RMS
//     difference far below the music), so wrapping at loopEnd is seamless;
//   - total size.
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'web', 'audio');
const WORK = fs.mkdtempSync(path.join(os.tmpdir(), 'ggmusic-'));
// Sunny Meadow's loops and the stingers stay at 80 kbps (byte-identical to the first release); the map
// loops (maps 2-10) are 64 kbps so all ten maps fit the phone budget (MAX_TOTAL).
const BITRATE = '80k', MAP_BITRATE = '64k';
const MAX_TOTAL = 6 * 1024 * 1024;
const TARGET = { loop: -20, stinger: -16 }, MAX_TP = -3;
const { MAP_LOOPS } = require('./gen.js');
const NAMES = { build: 'music-build', wave: 'music-wave', win: 'stinger-win', lose: 'stinger-lose' };
for (const m of MAP_LOOPS) for (const ph of ['build', 'wave']) NAMES[`${ph}-m${m.map}`] = `music-${ph}-m${m.map}`;

function ffmpegPath() {
  if (process.env.FFMPEG) return process.env.FFMPEG;
  try { execFileSync('ffmpeg', ['-version'], { stdio: 'ignore' }); return 'ffmpeg'; } catch (e) {}
  const win = '/mnt/c/ProgramData/chocolatey/bin/ffmpeg.exe';
  if (fs.existsSync(win)) return win;
  throw new Error('no ffmpeg: set FFMPEG');
}
const FF = ffmpegPath();
const winExe = FF.endsWith('.exe');
// A Windows ffmpeg needs Windows paths, and can't write into WSL's /tmp reliably: use a folder
// under the repo's out/ for its files in that case.
const p = f => (winExe ? execFileSync('wslpath', ['-w', f]).toString().trim() : f);
function ff(args) {
  return execFileSync(FF, ['-hide_banner', '-nostats', ...args], { stdio: ['ignore', 'pipe', 'pipe'],
    maxBuffer: 64 << 20 }).toString();
}
function ffErr(args) {   // ffmpeg prints filter reports on stderr
  try {
    const r = require('child_process').spawnSync(FF, ['-hide_banner', '-nostats', ...args], { maxBuffer: 64 << 20 });
    return r.stderr.toString();
  } catch (e) { return ''; }
}
function measure(file, from, to) {
  const trim = from !== undefined ? `atrim=start=${from}:end=${to},` : '';
  const s = ffErr(['-i', p(file), '-af', `${trim}ebur128=peak=true`, '-f', 'null', '-']);
  const sum = s.slice(s.lastIndexOf('Summary:'));
  const I = parseFloat((sum.match(/I:\s+(-?[\d.]+) LUFS/) || [])[1]);
  const TP = parseFloat((sum.match(/Peak:\s+(-?[\d.]+|-inf) dBFS/) || [])[1]);
  return { I, TP };
}
function readF32Wav(file) {
  const b = fs.readFileSync(file);
  let o = 12, fmt = null, data = null;
  while (o < b.length) {
    const id = b.toString('ascii', o, o + 4), n = b.readUInt32LE(o + 4);
    if (id === 'fmt ') fmt = { format: b.readUInt16LE(o + 8), ch: b.readUInt16LE(o + 10), rate: b.readUInt32LE(o + 12),
                               bits: b.readUInt16LE(o + 22) };
    if (id === 'data') data = b.subarray(o + 8, o + 8 + n);
    o += 8 + n + (n & 1);
  }
  if (!fmt || fmt.format !== 3 || fmt.bits !== 32 || fmt.ch !== 1) throw new Error('expected mono f32 wav: ' + file);
  const x = new Float32Array(data.length / 4);
  for (let i = 0; i < x.length; i++) x[i] = data.readFloatLE(i * 4);
  return { x, rate: fmt.rate };
}
const db = v => 20 * Math.log10(Math.max(v, 1e-12));
function rms(x, a, n) { let s = 0; for (let i = 0; i < n; i++) s += x[a + i] * x[a + i]; return Math.sqrt(s / n); }

function main() {
  const work = winExe ? path.join(__dirname, 'out') : WORK;
  fs.mkdirSync(work, { recursive: true });
  fs.mkdirSync(OUT, { recursive: true });
  execFileSync(process.execPath, [path.join(__dirname, 'gen.js'), '--out', work], { stdio: 'inherit' });
  const layout = JSON.parse(fs.readFileSync(path.join(work, 'layout.json'), 'utf8'));
  const manifest = { rate: 44100, about: 'Original music generated by tools/music/gen.js (no samples, no third-party ' +
    'audio). Loops: play from loopStart and loop [loopStart, loopEnd); the files are periodic around both points, ' +
    'so MP3 encoder padding cannot cause a gap. loop_start/loop_end are the same points in samples.' };
  // Which loops each map plays (map 1 = Sunny Meadow, also the menus). The players derive the same names
  // (build/wave for map 1, build-mN/wave-mN for map N); the tests check the two agree.
  manifest.maps = [{ map: 1, title: 'Sunny Meadow', build: 'build', wave: 'wave' }]
    .concat(MAP_LOOPS.map((m) => ({ map: m.map, title: m.title, build: `build-m${m.map}`, wave: `wave-m${m.map}` })));
  let fails = 0, total = 0;
  const check = (ok, what) => { console.log(`${ok ? 'PASS' : 'FAIL'} ${what}`); if (!ok) fails++; };
  for (const name of Object.keys(NAMES)) {
    const L = layout[name], wav = path.join(work, name + '.wav');
    const target = L.loop ? TARGET.loop : TARGET.stinger;
    const m = L.loop ? measure(wav, L.loopStart, L.loopEnd) : measure(wav);
    let gain = target - m.I;
    if (m.TP + gain > MAX_TP) gain = MAX_TP - m.TP;
    const mp3 = path.join(OUT, NAMES[name] + '.mp3');
    ff(['-y', '-i', p(wav), '-af', `volume=${gain.toFixed(3)}dB`, '-ac', '1', '-ar', '44100', '-c:a', 'libmp3lame',
        '-b:a', L.map > 1 ? MAP_BITRATE : BITRATE, '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:a', '+bitexact', p(mp3)]);
    const size = fs.statSync(mp3).size;
    total += size;
    // QA: decode again
    const dec = path.join(work, name + '-decoded.wav');
    ff(['-y', '-i', p(mp3), '-c:a', 'pcm_f32le', p(dec)]);
    const q = L.loop ? measure(dec, L.loopStart, L.loopEnd) : measure(dec);
    const entry = { file: NAMES[name] + '.mp3', seconds: L.seconds, key: L.key, bytes: size,
                    lufs: +q.I.toFixed(1), truePeak: +q.TP.toFixed(1), gainDb: +gain.toFixed(2) };
    if (L.loop) {
      Object.assign(entry, { map: L.map, loop: L.loopLength, loopStart: L.loopStart, loopEnd: L.loopEnd, bpm: L.bpm,
                             loop_start: Math.round(L.loopStart * 44100), loop_end: Math.round(L.loopEnd * 44100) });
      // (a) the SOURCE is exactly periodic: 0.4 s around loopStart equals the same window one loop
      //     later (in the MP3 the two windows differ by codec noise only, so that's checked as (b)).
      const src = readF32Wav(wav).x, rate = 44100;
      const n = Math.round(0.4 * rate), a = Math.round((L.loopStart - 0.2) * rate), Ls = Math.round(L.loopLength * rate);
      const diff = new Float32Array(n);
      for (let i = 0; i < n; i++) diff[i] = src[a + i] - src[a + Ls + i];
      entry.periodicDb = +(db(rms(diff, 0, n)) - db(rms(src, a, n))).toFixed(1);
      check(entry.periodicDb < -80, `${name}: source periodic across the loop point (${entry.periodicDb} dB)`);
      // (b) the decoded MP3 has no click at the splice: play [.. loopEnd) then [loopStart ..) and compare
      //     the sample-to-sample change in 3 ms windows at the splice with the windows around it.
      const x = readF32Wav(dec).x;
      const e = Math.round(L.loopEnd * rate), s0 = Math.round(L.loopStart * rate), h = Math.round(0.06 * rate);
      const y = new Float32Array(2 * h);
      for (let i = 0; i < h; i++) { y[i] = x[e - h + i]; y[h + i] = x[s0 + i]; }
      const w = Math.round(0.003 * rate), act = k => {
        let s = 0;
        for (let i = k; i < k + w - 1; i++) s += (y[i + 1] - y[i]) ** 2;
        return Math.sqrt(s / (w - 1));
      };
      const around = [];
      for (let k = 0; k + w < y.length; k += w) if (Math.abs(k + w / 2 - h) > 2 * w) around.push(act(k));
      around.sort((p1, p2) => p1 - p2);
      const typical = around[Math.floor(around.length * 0.9)];
      entry.spliceRatio = +(act(h - Math.floor(w / 2)) / typical).toFixed(2);
      // A loop whose bar 1 opens with a sharp attack (a plucked string) has a big sample-to-sample change at
      // loopStart in the music itself, splice or not. So also measure the SAME spot with no splice (the decoded
      // file played straight through loopStart): a click is the splice adding change the music doesn't have.
      for (let i = 0; i < 2 * h; i++) y[i] = x[s0 - h + i];
      entry.spliceVsMusic = +(entry.spliceRatio / (act(h - Math.floor(w / 2)) / typical)).toFixed(2);
      check(entry.spliceRatio < 1.5 || entry.spliceVsMusic < 1.1,
            `${name}: no click at the MP3 loop splice (change ${entry.spliceRatio}x the 90th percentile nearby, < 1.5; ` +
            `or ${entry.spliceVsMusic}x the same spot played without a splice, < 1.1)`);
      check(Math.abs(q.I - target) <= 1 || q.TP <= MAX_TP + 0.3, `${name}: ${q.I.toFixed(1)} LUFS (target ${target})`);
    } else {
      check(Math.abs(q.I - target) <= 1.5 || q.TP <= MAX_TP + 0.3, `${name}: ${q.I.toFixed(1)} LUFS (target ${target})`);
    }
    check(q.TP <= MAX_TP + 0.5, `${name}: true peak ${q.TP.toFixed(1)} dBTP (max ${MAX_TP}, +0.5 for MP3)`);
    manifest[name] = entry;
    console.log(name, JSON.stringify(entry));
  }
  check(total < MAX_TOTAL, `total size ${(total / 1024).toFixed(0)} KB (< ${MAX_TOTAL / 1024} KB)`);
  check(manifest.maps.length === 10 && new Set(manifest.maps.flatMap((m) => [m.build, m.wave])).size === 20 &&
        manifest.maps.every((m) => manifest[m.build] && manifest[m.wave]), 'every map has its own build and wave loop (20 loops)');
  fs.writeFileSync(path.join(OUT, 'music.json'), JSON.stringify(manifest, null, 1) + '\n');
  if (!winExe) fs.rmSync(WORK, { recursive: true, force: true });
  process.exit(fails ? 1 : 0);
}

main();
